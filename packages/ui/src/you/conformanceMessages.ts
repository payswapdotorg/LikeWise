const enUSMessages: Record<string, string> = {
  ...enUS,
  ...CONFORMANCE_DEMO_STEP_MESSAGES_EN_US,
};

const zhCNMessages: Record<string, string> = {
  ...zhCN,
  ...CONFORMANCE_DEMO_STEP_MESSAGES_ZH_CN,
};

const FALLBACK_MESSAGES = enUSMessages;

export function resolveConformanceMessages(locale: string): Record<string, string> {
  if (locale === "zh-CN") {
    return zhCNMessages;
  }
  return enUSMessages;
}

/** 与中央 IntlProvider 同款 `{key}` 占位符语义；缺失回退 en-US，再回退 id。 */
export function formatConformanceMessage(
  messages: Record<string, string>,
  id: string,
  values?: Record<string, string | number>,
): string {
  let text = messages[id] ?? FALLBACK_MESSAGES[id] ?? id;
  if (values) {
    for (const [key, value] of Object.entries(values)) {
      text = text.replaceAll(`{${key}}`, String(value));
    }
  }
  return text;
}
